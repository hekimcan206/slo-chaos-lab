using System.Globalization;
using System.Text;
using SloChaosLab.Slo;

namespace SloChaosLab.Chaos;

/// <summary>Markdown renderings of run results, pasted into the postmortems and docs/benchmarks.md.</summary>
internal static class Report
{
    private static readonly CultureInfo Ci = CultureInfo.InvariantCulture;

    public static string Single(RunResult r)
    {
        ArgumentNullException.ThrowIfNull(r);
        var sb = new StringBuilder();
        sb.Append(Ci, $"### {r.Title} ({r.Variant})\n\n");
        sb.Append(Ci, $"{r.RatePerSecond} req/s fixed, client timeout {r.ClientTimeoutSeconds:0.#} s; warm-up {r.WarmupSeconds:0} s, fault {r.FaultSeconds:0} s, recovery {r.RecoverySeconds:0} s. Fault: {r.Fault}.\n\n");
        sb.Append("Client-observed:\n\n");
        sb.Append("| phase | requests | 2xx | 5xx | timeouts | availability | p50 ms | p95 ms | p99 ms | p99 all ms | <=250 ms |\n");
        sb.Append("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n");
        foreach (var p in r.Client)
        {
            sb.Append(Ci, $"| {p.Phase} | {p.Requests} | {p.Succeeded} | {p.ServerErrors} | {p.ClientTimeouts + p.TransportErrors} | {Pct(p.Availability)} | {Ms(p.P50Ms)} | {Ms(p.P95Ms)} | {Ms(p.P99Ms)} | {Ms(p.P99AllMs)} | {Pct(p.LatencyCompliance[SloCatalog.LatencyP99.Name])} |\n");
        }

        sb.Append("\nServer-side SLI (Prometheus, counted when the request completes):\n\n");
        sb.Append("| phase | requests | 5xx | 499 (client gone) | availability | <=100 ms | <=250 ms |\n");
        sb.Append("|---|---:|---:|---:|---:|---:|---:|\n");
        foreach (var p in r.Server)
        {
            sb.Append(Ci, $"| {p.Phase} | {p.Requests:0} | {p.ServerErrors:0} | {p.ClientClosed:0} | {Pct(p.Availability)} | {Pct(p.LatencyCompliance[SloCatalog.LatencyP95.Name])} | {Pct(p.LatencyCompliance[SloCatalog.LatencyP99.Name])} |\n");
        }

        sb.Append("\n| SLO | budget consumed (client) | budget consumed (server) | max burn 5m | max burn 1h |\n|---|---:|---:|---:|---:|\n");
        foreach (var slo in SloCatalog.All)
        {
            sb.Append(Ci, $"| {slo.Name} | {Pct(r.BudgetConsumedClient[slo.Name])} | {Pct(r.BudgetConsumedServer[slo.Name])} | {r.MaxBurnRate5m[slo.Name]:0.#}x | {r.MaxBurnRate1h[slo.Name]:0.#}x |\n");
        }

        sb.Append("\n| alert | fired after fault start (measured) | last firing after fault end | steady-state model |\n|---|---:|---:|---:|\n");
        var names = r.Alerts.Select(a => a.Alert).Union(r.ModelledSteadyStateAlerts.Where(m => m.FirstFiringAfterFaultStartSeconds is not null).Select(m => m.Alert)).Order(StringComparer.Ordinal);
        foreach (var name in names)
        {
            var measured = r.Alerts.FirstOrDefault(a => a.Alert == name);
            var model = r.ModelledSteadyStateAlerts.FirstOrDefault(m => m.Alert == name);
            sb.Append(Ci, $"| {name} | {Sec(measured?.FirstFiringAfterFaultStartSeconds)} | {Sec(measured?.LastFiringAfterFaultEndSeconds)} | {Sec(model?.FirstFiringAfterFaultStartSeconds)} |\n");
        }

        if (!names.Any())
        {
            sb.Append("| (none fired) | | | |\n");
        }

        sb.Append(Ci, $"\nRecovered (10 s of all-2xx under 250 ms) {Sec(r.RecoveryAfterFaultSeconds)} after the fault ended. Host: {r.Host}.\n");
        return sb.ToString();
    }

    public static string Summary(IReadOnlyList<RunResult> results)
    {
        ArgumentNullException.ThrowIfNull(results);
        var sb = new StringBuilder();
        sb.Append("<!-- Generated by `dotnet run --project tools/SloChaosLab.Chaos -- report` from the JSON files in this folder. -->\n");
        sb.Append("# Experiment results\n\n");
        sb.Append("Fault-phase numbers, client-observed unless marked. Availability SLO 99.9 %, latency SLO 99 % within 250 ms.\n\n");
        sb.Append("| experiment | variant | availability | p50 ms | p95 ms | p99 ms | <=250 ms | budget used (avail.) | budget used (latency p99) | max burn 5m (avail. / p99) | page alert fired after | recovery |\n");
        sb.Append("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|\n");
        foreach (var r in results.OrderBy(r => Order(r.Experiment)).ThenBy(r => r.Variant == "before" ? 0 : 1))
        {
            var fault = r.Client.First(p => p.Phase == (r.Experiment == "baseline" ? "warmup" : "fault"));
            var pages = r.Alerts.Where(a => a.Alert.EndsWith("FastBurn", StringComparison.Ordinal) || a.Alert.EndsWith("SlowBurn", StringComparison.Ordinal))
                .Select(a => $"{a.Alert.Replace("LedgerPost", string.Empty, StringComparison.Ordinal)} {Sec(a.FirstFiringAfterFaultStartSeconds)}");
            sb.Append(Ci, $"| {r.Experiment} | {r.Variant} | {Pct(fault.Availability)} | {Ms(fault.P50Ms)} | {Ms(fault.P95Ms)} | {Ms(fault.P99Ms)} | {Pct(fault.LatencyCompliance[SloCatalog.LatencyP99.Name])} | ");
            sb.Append(Ci, $"{Pct(r.BudgetConsumedClient[SloCatalog.Availability.Name])} | {Pct(r.BudgetConsumedClient[SloCatalog.LatencyP99.Name])} | ");
            sb.Append(Ci, $"{r.MaxBurnRate5m[SloCatalog.Availability.Name]:0.#}x / {r.MaxBurnRate5m[SloCatalog.LatencyP99.Name]:0.#}x | {(pages.Any() ? string.Join("; ", pages) : "none")} | {Sec(r.RecoveryAfterFaultSeconds)} |\n");
        }

        foreach (var r in results.OrderBy(r => Order(r.Experiment)).ThenBy(r => r.Variant == "before" ? 0 : 1))
        {
            sb.Append('\n').Append(Single(r));
        }

        return sb.ToString();
    }

    public static string CapacityTable(IReadOnlyList<CapacityStep> steps)
    {
        ArgumentNullException.ThrowIfNull(steps);
        var sb = new StringBuilder("| offered req/s | achieved 2xx/s | errors | p50 ms | p95 ms | p99 ms | max ms |\n|---:|---:|---:|---:|---:|---:|---:|\n");
        foreach (var s in steps)
        {
            var p = s.Stats;
            sb.Append(Ci, $"| {s.OfferedRatePerSecond} | {p.ThroughputPerSecond:0.0} | {p.Requests - p.Succeeded} | {Ms(p.P50Ms)} | {Ms(p.P95Ms)} | {Ms(p.P99Ms)} | {Ms(p.MaxMs)} |\n");
        }

        return sb.ToString();
    }

    private static int Order(string experiment) => experiment switch
    {
        "baseline" => 0,
        "latency" => 1,
        "jitter" => 2,
        "bandwidth" => 3,
        "reset" => 4,
        "partition" => 5,
        _ => 9,
    };

    private static string Pct(double fraction) => double.IsNaN(fraction) ? "n/a" : (fraction * 100).ToString("0.###", Ci) + " %";

    private static string Ms(double ms) => double.IsNaN(ms) ? "n/a" : ms.ToString(ms < 100 ? "0.0" : "0", Ci);

    private static string Sec(double? seconds) => seconds is null ? "-" : seconds.Value.ToString("0", Ci) + " s";
}
